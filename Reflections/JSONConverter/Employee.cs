namespace Reflections;

public class Employee
{
    private int empId;
    private string empName;
    private double empSalary;

    // Constructor
    public Employee(int empId, string empName, double empSalary)
    {
        this.empId = empId;
        this.empName = empName;
        this.empSalary = empSalary;
    }
}
